/**
 * Returns all templates for static paths or listing
 */
export function getAllTemplates(): StarterTemplate[] {
  return STARTER_TEMPLATES;
}

/**
 * Get templates for a specific category
 */
export function getTemplatesByCategory(category: GoalCategory): StarterTemplate[] {
  return STARTER_TEMPLATES.filter((t) => t.category === category);
}

/**
 * Get a single template by slug or id
 */
export function getTemplateBySlug(slugOrId: string): StarterTemplate | undefined {
  return STARTER_TEMPLATES.find((t) => t.slug === slugOrId || t.id === slugOrId);
}

/**
 * Assembles the full prompt text specifically formatted for the template's target model
 */
export function getTemplateAssembledPrompt(template: StarterTemplate): string {
  const modelName = template.recommendedModel.toLowerCase();

  // Special visual formatting for Midjourney
  if (modelName.includes('midjourney')) {
    const parts = [
      template.fields.task || '',
      template.fields.role ? `Visual Direction: ${template.fields.role}` : '',
      template.fields.tone ? `Lighting & Atmosphere: ${template.fields.tone}` : '',
      template.fields.outputFormat ? `Composition: ${template.fields.outputFormat}` : '',
      template.fields.constraints || '',
    ].filter(Boolean);
    return `/imagine prompt: ${parts.join(', ')}`;
  }

  // Special visual formatting for Video Models (Sora, Runway)
  if (modelName.includes('sora') || modelName.includes('runway')) {
    return [
      `[AI Video Direction Prompt]`,
      `Camera Direction: ${template.fields.role || ''}`,
      `Subject & Action: ${template.fields.task || ''}`,
      `Lighting & Atmosphere: ${template.fields.tone || ''}`,
      `Technical Constraints: ${template.fields.constraints || ''}`,
      `Output Format: ${template.fields.outputFormat || ''}`,
    ].filter(Boolean).join('\n\n');
  }

  // Standard LLM formats via TargetModel mapping
  let targetModel = TargetModel.Generic;
  if (modelName.includes('claude')) targetModel = TargetModel.Claude;
  else if (modelName.includes('chatgpt') || modelName.includes('gpt')) targetModel = TargetModel.ChatGPT;
  else if (modelName.includes('gemini')) targetModel = TargetModel.Gemini;
  else if (modelName.includes('llama')) targetModel = TargetModel.Llama;
  else if (modelName.includes('mistral')) targetModel = TargetModel.Mistral;
  else if (modelName.includes('deepseek')) targetModel = TargetModel.DeepSeek;

  return assemblePrompt(
    template.fields as PromptFields,
    template.recommendedFramework,
    targetModel
  );
}
